/// Returns true for a known method, accepting Telegram's case-insensitive
/// method spelling without allocating a normalized copy.
#[inline]
pub fn is_bot_api_method(method: &str) -> bool {
    BOT_API_METHODS
        .iter()
        .any(|known| known.eq_ignore_ascii_case(method))
}

/// Returns true for methods with a direct typed parser in trbotapi-core.
#[inline]
pub fn is_typed_method(method: &str) -> bool {
    [
        "getMe",
        "sendMessage",
        "getUpdates",
        "setWebhook",
        "deleteWebhook",
        "getWebhookInfo",
        "answerCallbackQuery",
        "getChat",
    ]
    .iter()
    .any(|known| known.eq_ignore_ascii_case(method))
}
